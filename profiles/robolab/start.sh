#!/usr/bin/env bash
set -euo pipefail
PROFILE_DIR="$(cd "$(dirname "$0")" && pwd)"
source "$PROFILE_DIR/profile.env"
source "${PROFILE_ENV_FILE:-$PROFILE_DIR/.env}"
PROFILE_ENV_FILE="${PROFILE_ENV_FILE:-$PROFILE_DIR/.env}" "$PROFILE_DIR/validate.sh"
export DSPARK_VLLM_IMAGE="$ROBOLAB_IMAGE"
export DSPARK_RUNTIME_LANE=native-v026 DSPARK_QUALIFICATION_MODE=production
export EXPECTED_INTEGRATED_VLLM_COMMIT EXPECTED_MODEL_REVISION EXPECTED_VLLM_VERSION
export EXPECTED_IMAGE_SOURCE_REVISION="$EXPECTED_SOURCE_REVISION"
export EXPECTED_RUNTIME_AUDIT_MANIFEST_SHA256
export RUNTIME_AUDIT_MANIFEST="$ROBOLAB_CHECKOUT/recipe/runtime-manifest.vllm-sm121.3.json"
export DSPARK_RUNTIME_AUDIT_MANIFEST="$RUNTIME_AUDIT_MANIFEST"
export MASTER_ADDR WORKER_HOST MASTER_PORT HF_CACHE DSPARK_MODEL_DIR DSPARK_HEAD_MODEL_DIR DSPARK_WORKER_MODEL_DIR
export HEAD_ETH_IF WORKER_ETH_IF HEAD_IB_HCA WORKER_IB_HCA NCCL_IB_GID_INDEX SERVED_MODEL_NAME
export MAX_MODEL_LEN=327680 MAX_NUM_SEQS=16 MAX_NUM_BATCHED_TOKENS=16384
export GPU_MEMORY_UTILIZATION=0.835 KV_CACHE_MEMORY_BYTES=15998753178 MTP_NUM_TOKENS=6
"$ROBOLAB_CHECKOUT/scripts/run-dspark-dual-gb10.sh"
for _ in $(seq 1 120); do
  if curl -fsS --max-time 5 http://127.0.0.1:8888/v1/models \
      | jq -e '.data | any(.id == "deepseek-v4-flash-dspark")' >/dev/null 2>&1; then
    exit 0
  fi
  sleep 15
done
echo 'error: timed out waiting for r0b0lab API readiness' >&2
exit 1
